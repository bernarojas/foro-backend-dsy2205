--  Se puede volver a ejecutar: borra las tablas antes de crearlas.
--
--  Dueño de cada tabla:
--    ms-usuarios -> FORO_ROL, FORO_USUARIO
--    ms-foro     -> FORO_CATEGORIA, FORO_TEMA, FORO_COMENTARIO
--  Entre los dos microservicios no hay llaves foráneas: el tema y el
--  comentario guardan el id y el nombre del autor que viene en el token.
--
--  Todos los usuarios de prueba tienen la clave:  Duoc2026!
-- =====================================================================

SET DEFINE OFF;

-- ---------------------------------------------------------------------
-- Borrar lo anterior (en orden inverso por las llaves foráneas)
-- ---------------------------------------------------------------------
BEGIN
  FOR t IN (SELECT table_name FROM user_tables
             WHERE table_name IN ('FORO_COMENTARIO', 'FORO_TEMA', 'FORO_CATEGORIA',
                                  'FORO_USUARIO', 'FORO_ROL')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- =====================================================================
--  MICROSERVICIO DE USUARIOS
-- =====================================================================

CREATE TABLE FORO_ROL (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE       VARCHAR2(30)  NOT NULL,
  DESCRIPCION  VARCHAR2(200),
  CONSTRAINT UQ_ROL_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE FORO_USUARIO (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE          VARCHAR2(100) NOT NULL,
  EMAIL           VARCHAR2(120) NOT NULL,
  PASSWORD_HASH   VARCHAR2(100) NOT NULL,
  ROL_ID          NUMBER        NOT NULL,
  ESTADO          VARCHAR2(15)  DEFAULT 'ACTIVO' NOT NULL,
  FECHA_REGISTRO  TIMESTAMP     DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Santiago' AS TIMESTAMP) NOT NULL,
  CONSTRAINT UQ_USUARIO_EMAIL UNIQUE (EMAIL),
  CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ROL_ID) REFERENCES FORO_ROL (ID),
  CONSTRAINT CK_USUARIO_ESTADO CHECK (ESTADO IN ('ACTIVO', 'BLOQUEADO'))
);

CREATE INDEX IX_USUARIO_ROL ON FORO_USUARIO (ROL_ID);

-- =====================================================================
--  MICROSERVICIO DEL FORO
-- =====================================================================

CREATE TABLE FORO_CATEGORIA (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE       VARCHAR2(60)  NOT NULL,
  DESCRIPCION  VARCHAR2(250),
  CONSTRAINT UQ_CATEGORIA_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE FORO_TEMA (
  ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CATEGORIA_ID         NUMBER         NOT NULL,
  AUTOR_ID             NUMBER         NOT NULL,
  AUTOR_NOMBRE         VARCHAR2(100)  NOT NULL,
  TITULO               VARCHAR2(150)  NOT NULL,
  CONTENIDO            VARCHAR2(4000) NOT NULL,
  ESTADO               VARCHAR2(15)   DEFAULT 'PUBLICADO' NOT NULL,
  FECHA_CREACION       TIMESTAMP      DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Santiago' AS TIMESTAMP) NOT NULL,
  FECHA_ACTUALIZACION  TIMESTAMP,
  CONSTRAINT FK_TEMA_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES FORO_CATEGORIA (ID),
  CONSTRAINT CK_TEMA_ESTADO CHECK (ESTADO IN ('PUBLICADO', 'BANEADO'))
);

CREATE INDEX IX_TEMA_CATEGORIA ON FORO_TEMA (CATEGORIA_ID);
CREATE INDEX IX_TEMA_AUTOR     ON FORO_TEMA (AUTOR_ID);

CREATE TABLE FORO_COMENTARIO (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TEMA_ID         NUMBER         NOT NULL,
  AUTOR_ID        NUMBER         NOT NULL,
  AUTOR_NOMBRE    VARCHAR2(100)  NOT NULL,
  CONTENIDO       VARCHAR2(2000) NOT NULL,
  ESTADO          VARCHAR2(15)   DEFAULT 'PUBLICADO' NOT NULL,
  FECHA_CREACION  TIMESTAMP      DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE 'America/Santiago' AS TIMESTAMP) NOT NULL,
  CONSTRAINT FK_COMENTARIO_TEMA FOREIGN KEY (TEMA_ID) REFERENCES FORO_TEMA (ID) ON DELETE CASCADE,
  CONSTRAINT CK_COMENTARIO_ESTADO CHECK (ESTADO IN ('PUBLICADO', 'BANEADO'))
);

CREATE INDEX IX_COMENTARIO_TEMA ON FORO_COMENTARIO (TEMA_ID);

